// Stage 5 v4 genuine-fixture proof (actual entry -> WorldService bridge).
//
// Producer leg: the shared `recordStage5V4Chain` recorder drives the real
// `startWorldAdapterEntry` facts/gesture lanes through the real
// `broker_world_eval` bridge (`DiscoverWorld` handshake+settings,
// `DescribeWorld` captures, `ReadWorldPresentation` reads; exactly those
// three methods). The regenerated full chain
// (p5,p6,cover,preview,cover2,a2,a3,preview-b) and s2 chain
// (p5,p6,cover,preview,s2) must equal the checked-in genuine counterpart
// fixtures in `test-fixtures/stage5-v4/{full,s2}`: every step envelope and
// genesis-0 byte-exact after top-level `gen`/`source` nonce normalization
// only (`sourceSeq`/`nativeInvalid`/clocks/rev/facts/witness stay exact),
// projections `gen`-only normalized (`req` is scripted deterministic).
// Genesis-1 is never byte-compared: its frame/member/view/clear/creation
// attempt stamps are adopted from the preceding broker reply clock
// (`world-apply` stamps every mechanical attempt of an apply turn with
// `state.lastClock`), so the test pins attempt target/readback bytes
// field-wise plus frame stamps equal to the genesis-0 reply clock and
// at/below the genesis-1 reply clock instead. Intent stays
// disabled (no intent writes, no auth/native evidence); the empty intent
// lane is pinned by the same byte equality. The recorder's
// strict parser already proved every regenerated byte is broker-accepted.
//
// An idle gesture answer is an omission lane, never a terminal
// release/cancel/commit: the broker map persists and the broker omits the
// gesture (barrier down) while the drained idle A/0 snapshot still rides
// the envelope for correlation, so cover2 lands witness 2 idle-omitted
// while A stays live and a2 recovers the identical A/1 (the
// coverage-current drain). A null nativeGesture remains the absent shape of
// p5/p6/cover only. No step in either chain ever sends released/cancelled.
//
// Subscriber leg: the genuine recorded `projection-*.json` broker bytes are
// routed through the real `createWorldPresentationSubscriber`; each rendered
// native DTO must equal an independent expected payload built in this test
// from the projection fields under the documented `SetPresentation`
// formatter contract (never by calling the production formatter). The v2
// border forwards the exact anchored descriptor (boolean `visible`).
//
// V2 dispatch siblings: `test-fixtures/stage5-v2/{full,s2}/dispatch-*.json`
// are the genuine v2 subscriber renders of the checked-in v2 projections
// (produced by the dispatch recorder through the same production
// subscriber, `req` re-keyed, no direct formatter calls). Each v2 case
// below also byte-compares the paint to its dispatch sibling with only the
// volatile `gen` normalized.
//
// Correlation seam (disclosed, shape-preserving): the subscriber mints a
// per-read `req` nonce, so each read is answered with the recorded
// projection bytes re-keyed to the issued `req` only. The native DTO
// carries no `req`, so rendered bytes stay exactly comparable.

