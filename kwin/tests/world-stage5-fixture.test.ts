// Volatile transport/correlation tokens (disclosed, shape-preserving):
// the broker mints a fresh `gen` per run and the entry mints a per-run
// `source` nonce, so regenerated step bytes are compared with exactly
// those top-level tokens normalized. Every causal byte (report, witness,
// gesture lanes, windows, sourceSeq/nativeInvalid watermarks) must match
// exactly.
function normalizeTopLevel(
    emitted: string,
    recorded: string,
    tokens: ReadonlyArray<string>,
): { actual: string; expected: string } {
    const actualValue = JSON.parse(emitted) as Record<string, unknown>;
    const recordedValue = JSON.parse(recorded) as Record<string, unknown>;
    for (const token of tokens) {
        assert.ok(token in recordedValue, `genuine fixture carries ${token}`);
        assert.ok(token in actualValue, `regenerated bytes carry ${token}`);
        actualValue[token] = recordedValue[token];
    }
    return { actual: JSON.stringify(actualValue), expected: recorded };
}

function parseReport(envelopeBytes: string): Record<string, unknown> {
    const envelope = JSON.parse(envelopeBytes) as Record<string, unknown>;
    return envelope["report"] as Record<string, unknown>;
}

const ATTEMPT_LANES = [
    "frameAttempts",
    "memberAttempts",
    "viewAttempts",
    "clearAttempts",
    "creationAttempts",
] as const;

function attemptLane(report: Record<string, unknown>, lane: string): Array<Record<string, unknown>> {
    const value = report[lane];
    if (value === undefined) {
        return [];
    }
    assert.ok(Array.isArray(value), `report lane ${lane} is a list`);
    return value as Array<Record<string, unknown>>;
}

function assertNoAttempts(report: Record<string, unknown>, where: string): void {
    for (const lane of ATTEMPT_LANES) {
        assert.deepEqual(attemptLane(report, lane), [], `${where} carries no ${lane}`);
    }
}

function assertU64Le(a: string, b: string, where: string): void {
    assert.match(a, /^[0-9]+$/, `${where} is a canonical u64`);
    assert.match(b, /^[0-9]+$/, `${where} bound is a canonical u64`);
    assert.ok(BigInt(a) <= BigInt(b), `${where}: ${a} <= ${b}`);
}

// Genesis-1 attempt proof: attempt bytes are never stripped or normalized
// for a byte-compare (the stamps are adopted from the preceding broker
// reply clock, an independent recording epoch the test must not rewrite).
// Instead every attempt lane must match the genuine fixture lane in length
// and in all bytes except `attemptMs`, every frame stamp must equal the
// genesis-0 reply clock (the accepted origin of this apply turn), frame
// targets must match the capture's own window rects with echoing
// readbacks, stamps must be monotonic within each lane, and the maximum
// stamp must land at/below the capture's broker reply clock (the broker's
// own freshness gate accepted this capture in the live run).
function assertGenesisAttempts(
    regenerated: string,
    recorded: string,
    expectedStamp: string,
    replyClock: string,
    where: string,
): void {
    const regenReport = parseReport(regenerated);
    const recordedReport = parseReport(recorded);
    let maxStamp: string | null = null;
    for (const lane of ATTEMPT_LANES) {
        const regen = attemptLane(regenReport, lane);
        const fixture = attemptLane(recordedReport, lane);
        assert.equal(regen.length, fixture.length, `${where} ${lane} lane length matches the genuine fixture`);
        let previous: string | null = null;
        for (let i = 0; i < regen.length; i += 1) {
            const actual = regen[i] as Record<string, unknown> | undefined;
            const expected = fixture[i] as Record<string, unknown> | undefined;
            assert.ok(actual !== undefined && expected !== undefined, `${where} ${lane}[${i}] exists`);
            const stamp = actual["attemptMs"];
            assert.ok(typeof stamp === "string", `${where} ${lane}[${i}] stamps attemptMs`);
            if (previous !== null) {
                assertU64Le(previous, stamp, `${where} ${lane} stamps monotonic`);
            }
            previous = stamp;
            if (maxStamp === null) {
                maxStamp = stamp;
            } else {
                assert.match(stamp, /^[0-9]+$/);
                assert.match(maxStamp, /^[0-9]+$/);
                if (BigInt(stamp) > BigInt(maxStamp)) {
                    maxStamp = stamp;
                }
            }
            const restActual = { ...actual };
            delete restActual["attemptMs"];
            const restExpected = { ...expected };
            delete restExpected["attemptMs"];
            assert.deepEqual(restActual, restExpected, `${where} ${lane}[${i}] target/readback matches`);
        }
    }
    const frames = attemptLane(regenReport, "frameAttempts");
    assert.ok(frames.length > 0, `${where} carries genuine frame writes from accepted startup`);
    for (const attempt of frames) {
        const frameStamp = attempt["attemptMs"];
        assert.ok(typeof frameStamp === "string", `${where} frame attempt stamps attemptMs`);
        assert.equal(frameStamp, expectedStamp, `${where} frame stamp equals the genesis-0 reply clock`);
    }
    assertU64Le(expectedStamp, replyClock, `${where} genesis-0 clock precedes the genesis-1 reply clock`);
    const windows = regenReport["windows"] as Array<Record<string, unknown>>;
    const targets = frames.map((attempt) => JSON.stringify(attempt["target"])).sort();
    const rects = windows.map((row) => JSON.stringify(row["rect"])).sort();
    assert.deepEqual(targets, rects, `${where} frame targets match the captured window rects`);
    for (const attempt of frames) {
        assert.deepEqual(
            attempt["readback"],
            attempt["target"],
            `${where} frame readback echoes the accepted write`,
        );
    }
    assert.ok(maxStamp !== null, `${where} stamped at least one attempt`);
    assertU64Le(maxStamp, replyClock, `${where} attempt stamps land at/below the broker reply clock`);
}

interface GestureExpectation {
    readonly instance: string;
    readonly serial: string;
    readonly phase: "updated" | "idle";
}

interface StepExpectation {
    readonly witness: string;
    readonly gesture: GestureExpectation | null;
}

function assertReportWitnessGesture(
    report: Record<string, unknown>,
    expected: StepExpectation,
    where: string,
): void {
    const witness = report["nativeInvalidWitness"] as { instance: string; counter: string } | null;
    assert.deepEqual(
        witness,
        { instance: "effect-1", counter: expected.witness },
        `${where} covers the genuine facts witness`,
    );
    const gesture = report["nativeGesture"] as
        | { instance: string; serial: string; phase: string; win: string }
        | null;
    const barrier = report["gesture"] as boolean;
    if (expected.gesture === null) {
        assert.equal(gesture, null, `${where} carries no gesture`);
        assert.equal(barrier, false, `${where} report gesture barrier down`);
    } else {
        assert.ok(gesture !== null, `${where} carries the drained gesture snapshot`);
        assert.equal(gesture.instance, expected.gesture.instance, `${where} gesture instance`);
        assert.equal(gesture.serial, expected.gesture.serial, `${where} gesture serial`);
        assert.equal(gesture.phase, expected.gesture.phase, `${where} gesture phase`);
        if (expected.gesture.phase === "idle") {
            // Idle omission: the broker omits the gesture (barrier down)
            // while the drained idle snapshot still rides for correlation.
            assert.equal(gesture.win, "", `${where} idle gesture wins nothing`);
            assert.equal(barrier, false, `${where} report gesture barrier down`);
        } else {
            assert.equal(barrier, true, `${where} report gesture barrier up`);
        }
    }
}

