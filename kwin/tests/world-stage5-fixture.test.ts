// Independent expected-payload oracle: rebuilds the exact native
// `SetPresentation` DTO from the genuine projection fields following the
// documented formatter contract
// ({v:2,gen,rev,obs,coveredInstance,coveredInvalid,foreground,
// border:{visible,reason,subject,outsets,width,radius,witness},
// underlay:{status:"found",win,outer,members:[win,...]}|{status:"hidden"},
// preview:{rect,sourceOut,sourceWs,win,producerInstance,producerSerial}|null}),
// never by calling the production formatter. Full DTO equality, all keys.
// The border forwards exactly unchanged, even with null or unjoined
// witness; native event authority owns the narrow hide.
function expectedNativePayload(proj: V4Projection, includePreview: boolean): string {
    const borderIn = proj.presentation.border;
    const borderOut: unknown = {
        visible: borderIn.visible,
        reason: borderIn.reason,
        subject: borderIn.subject,
        outsets: borderIn.outsets === null ? null : [...borderIn.outsets],
        width: borderIn.width,
        radius: borderIn.radius,
        witness: borderIn.witness === null
            ? null
            : {
                win: borderIn.witness.win,
                obs: borderIn.witness.obs,
                frame: [...borderIn.witness.frame],
                foreground: borderIn.witness.foreground,
            },
    };
    const underlay = proj.presentation.underlay;
    let underlayOut: unknown;
    if (underlay.status === "found") {
        const members = underlay.members as Array<{ win: string }>;
        underlayOut = {
            status: "found",
            win: underlay.win,
            outer: [...(underlay.outer as Array<number>)],
            members: members.map((member) => member.win),
        };
    } else {
        underlayOut = { status: "hidden" };
    }
    const sourcePreview = proj.preview;
    const previewOut = sourcePreview === null || !includePreview
        ? null
        : {
            rect: [...sourcePreview.rect],
            sourceOut: sourcePreview.sourceOut,
            sourceWs: sourcePreview.sourceWs,
            win: sourcePreview.win,
            producerInstance: sourcePreview.producerInstance,
            producerSerial: sourcePreview.producerSerial,
        };
    return JSON.stringify({
        v: 2,
        gen: proj.gen,
        rev: proj.rev,
        obs: proj.obs,
        coveredInstance: proj.coveredInstance,
        coveredInvalid: proj.coveredInvalid,
        foreground: proj.presentation.foreground,
        border: borderOut,
        underlay: underlayOut,
        preview: previewOut,
    });
}

function makeSubscriberHarness(opts: {
    invalidation: { instance: string; counter: string } | null;
    gesture: { instance: string; serial: string; coreId: string } | null;
    generation: string;
}): {
    paints: string[];
    answerChain: (chain: ChainName, name: string) => void;
    stop: () => void;
} {
    const pending: Array<{ payload: string; callback: (reply: unknown) => void }> = [];
    const paints: string[] = [];
    const sub = createWorldPresentationSubscriber({
        callDbus: (_s, _p, _i, _m, payload, callback) => {
            pending.push({ payload, callback });
        },
        getGeneration: () => opts.generation,
        getInvalidation: () => opts.invalidation,
        getGestureIdentity: () => opts.gesture,
        isStopped: () => false,
        log: () => undefined,
        scheduleOnce: () => () => undefined,
        renderer: {
            renderPresentation: (payload) => {
                paints.push(payload);
                return true;
            },
            hidePresentation: () => undefined,
            clearPresentation: () => undefined,
        },
    });
    sub.notifyGeneration(opts.generation);
    return {
        paints,
        answerChain: (chain: ChainName, name: string) => {
            for (const call of pending.splice(0)) {
                const issued = (JSON.parse(call.payload) as { req: string }).req;
                const recorded = JSON.parse(v4Fixture(chain, name)) as Record<string, unknown>;
                recorded["req"] = issued;
                call.callback(JSON.stringify(recorded));
            }
        },
        stop: () => {
            sub.stop();
        },
    };
}

interface SubscriberCase {
    readonly chain: ChainName;
    readonly projection: string;
    // Latest native invalidation known to the subscriber seam.
    readonly witness: string;
    // Coverage the genuine projection must carry; defaults to the latest
    // native witness (fresh cases). The stale case sets this explicitly
    // below the native witness so the subscriber must skip the paint.
    readonly covered?: string;
    readonly gesture: { readonly instance: string; readonly serial: string; readonly coreId: string } | null;
    readonly expectPreview: boolean;
    readonly expectPaints: number;
}

function runSubscriberCase(spec: SubscriberCase, where: string): void {
    const proj = JSON.parse(v4Fixture(spec.chain, spec.projection)) as V4Projection;
    const covered = spec.covered ?? spec.witness;
    assert.equal(proj.coveredInstance, "effect-1", `${where} genuine coverage instance`);
    assert.equal(proj.coveredInvalid, covered, `${where} genuine coverage witness`);
    // Gesture-barrier oracle (unweakened): every window row holds on the
    // gesture barrier exactly while a preview is live, else holds nothing.
    const wantHold = proj.preview === null ? "" : "gesture-barrier";
    assert.ok(proj.windows.length > 0, `${where} genuine projection carries window rows`);
    for (const row of proj.windows) {
        assert.equal(row.frame_hold, wantHold, `${where} row ${row.win} frame_hold`);
    }
    const h = makeSubscriberHarness({
        invalidation: { instance: "effect-1", counter: spec.witness },
        gesture: spec.gesture,
        generation: proj.gen,
    });
    try {
        h.answerChain(spec.chain, spec.projection);
        assert.equal(h.paints.length, spec.expectPaints, `${where} paint count`);
        if (spec.expectPaints === 0) {
            return;
        }
        const paint = h.paints[0] as string | undefined;
        assert.ok(paint !== undefined, `${where} painted`);
        assert.equal(paint, expectedNativePayload(proj, spec.expectPreview), `${where} native DTO bytes`);
        const rendered = JSON.parse(paint) as RenderedPayload;
        // V2 forwards the exact anchored descriptor (boolean visible).
        const expectedBorder = JSON.parse(expectedNativePayload(proj, spec.expectPreview)) as RenderedPayload;
        assert.deepEqual(rendered.border, expectedBorder.border, `${where} border forwarded`);
        // Real underlay: found for the tiled win-a group with both members
        // and verbatim outer geometry, intact even when preview strips.
        assert.equal(rendered.underlay["status"], "found", `${where} underlay found`);
        assert.equal(rendered.underlay["win"], "win-a", `${where} underlay group`);
        const members = rendered.underlay["members"] as Array<string>;
        assert.deepEqual([...members].sort(), ["win-a", "win-b"], `${where} underlay members`);
        assert.deepEqual(
            rendered.underlay["outer"],
            proj.presentation.underlay.outer,
            `${where} underlay geometry verbatim`,
        );
        if (spec.expectPreview) {
            const sourcePreview = proj.preview;
            assert.ok(sourcePreview !== null, `${where} genuine projection carries a preview`);
            assert.deepEqual(
                rendered.preview,
                {
                    rect: [...sourcePreview.rect],
                    sourceOut: sourcePreview.sourceOut,
                    sourceWs: sourcePreview.sourceWs,
                    win: sourcePreview.win,
                    producerInstance: sourcePreview.producerInstance,
                    producerSerial: sourcePreview.producerSerial,
                },
                `${where} preview forwarded exactly`,
            );
            assert.ok(spec.gesture !== null, `${where} live producer exists`);
            assert.equal(
                sourcePreview.producerInstance,
                spec.gesture.instance,
                `${where} preview producer instance`,
            );
            assert.equal(
                sourcePreview.producerSerial,
                spec.gesture.serial,
                `${where} preview producer serial`,
            );
        } else {
            assert.equal(rendered.preview, null, `${where} preview stripped`);
        }
    } finally {
        h.stop();
    }
}

