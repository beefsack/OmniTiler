//! Deterministic emitters for KDE checked-in artifacts.
//!
//! Every value the outputs carry (defaults, bounds, enum tokens and enum
//! order) derives from the shared catalog through
//! [`crate::kde_adapter`]; the adapter contributes only KDE placement
//! (keys, widgets, row order) and genuinely different native labels/tips.
//! Native schema formatting is preserved by type-aware rendering (see
//! [`rendered_default`]). No timestamps or nondeterministic metadata:
//! identical inputs always produce identical bytes.

use crate::kde_adapter::{
    self, GROUP_EFFECT, KDE_EXPOSED_FIELDS, KDE_NATIVE_PANELS, KDE_SCHEMA_ONLY_FIELD,
    KDE_SCHEMA_ONLY_KEY, KDE_SCHEMA_ONLY_LABEL, KDE_TABS, NATIVE_ONLY_KCFG_DEFAULT,
    NATIVE_ONLY_KCFG_KEY, NATIVE_ONLY_KCFG_LABEL, NATIVE_ONLY_SCHEMA_CHOICES,
    NATIVE_ONLY_SCHEMA_DEFAULT, NATIVE_ONLY_SCHEMA_KEY, NATIVE_ONLY_SCHEMA_LABEL,
    TILING_TAB_UI_SOURCE, kde_catalog_def, kde_field, kde_option_text,
};
use tiler_core::settings_catalog::{self, FieldDef, FieldType, SettingValue};

/// Provenance marker shared by the generated XML schemas.
pub const GENERATED_XML_MARKER: &str =
    "<!-- Generated by tiler-kde-settings-exporter from the shared catalog. Do not edit. -->";

/// One artifact emitter: deterministic catalog-to-file rendering.
pub type ArtifactEmitter = fn() -> String;

/// Checked-in artifact path plus its emitter, in stable order.
pub const ARTIFACTS: &[(&str, ArtifactEmitter)] = &[
    ("kwin/native-effect/activeborderconfig.kcfg", emit_kcfg),
    ("kwin/contents/config/main.xml", emit_main_xml),
    (
        "kwin/native-effect/generated/kde_settings_descriptors.h",
        emit_descriptors_header,
    ),
];

/// Byte comparison used by `--check` and the drift regression test.
#[must_use]
pub fn contents_match(current: &str, emitted: &str) -> bool {
    current == emitted
}

/// Render one catalog default exactly as the native schemas write it:
/// booleans and integers plainly, enum tokens and colors verbatim, doubles
/// with the existing native formatting (one decimal place, except the
/// follow-border sentinel which the kcfg writes as `-1`).
#[must_use]
pub fn rendered_default(def: &FieldDef) -> String {
    match def.default {
        SettingValue::Bool(got) => got.to_string(),
        SettingValue::Int(got) => got.to_string(),
        SettingValue::Float(got) => {
            if got == -1.0 {
                "-1".to_owned()
            } else if got.fract() == 0.0 {
                format!("{got:.1}")
            } else {
                got.to_string()
            }
        }
        SettingValue::Text(got) => got.to_owned(),
    }
}

fn kcfg_header() -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         {GENERATED_XML_MARKER}\n\
         <kcfg xmlns=\"http://www.kde.org/standards/kcfg/1.0\"\n\
         {space}xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"\n\
         {space}xsi:schemaLocation=\"http://www.kde.org/standards/kcfg/1.0\n\
         {cont:>26}http://www.kde.org/standards/kcfg/1.0/kcfg.xsd\">\n",
        space = "      ",
        cont = "",
    )
}

/// Emit `activeborderconfig.kcfg`: catalog defaults with exact KDE keys,
/// types and schema labels in native entry order, plus the retained
/// native-only preview entry in place.
#[must_use]
pub fn emit_kcfg() -> String {
    let mut out = kcfg_header();
    out.push_str("    <kcfgfile arg=\"true\"/>\n");
    out.push_str("    <group name=\"Effect-omnitiler-active-border\">\n");
    // Adapter order is native entry order; the retained native-only
    // preview row is spliced in where it stands today.
    for field in KDE_EXPOSED_FIELDS
        .iter()
        .filter(|field| field.group == GROUP_EFFECT)
    {
        let def = kde_catalog_def(field).expect("catalog def");
        out.push_str(&kcfg_entry(
            field.key,
            field.schema_type,
            field.schema_label,
            &rendered_default(def),
        ));
        if field.key == "UseThemeColor" {
            out.push_str(&kcfg_entry(
                NATIVE_ONLY_KCFG_KEY,
                "Color",
                NATIVE_ONLY_KCFG_LABEL,
                NATIVE_ONLY_KCFG_DEFAULT,
            ));
        }
    }
    out.push_str("    </group>\n</kcfg>\n");
    out
}

fn kcfg_entry(key: &str, schema_type: &str, label: &str, default: &str) -> String {
    format!(
        "        <entry name=\"{key}\" type=\"{schema_type}\">\n\
         {space}<label>{label}</label>\n\
         {space}<default>{default}</default>\n\
         {space2}</entry>\n",
        space = "            ",
        space2 = "        ",
    )
}

fn schema_header() -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         {GENERATED_XML_MARKER}\n\
         <kcfg xmlns=\"http://www.kde.org/standards/kcfg/1.0\"\n\
         {space}xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"\n\
         {space}xsi:schemaLocation=\"http://www.kde.org/standards/kcfg/1.0\n\
         {cont:>26}http://www.kde.org/standards/kcfg/1.0/kcfg.xsd\">\n",
        space = "      ",
        cont = "",
    )
}

/// Emit `contents/config/main.xml`: catalog defaults/tokens/bounds in
/// native entry order with native schema labels/tooltips, the catalog-owned
/// schema-only `defaultTiled` entry, and the retained hidden
/// `shortcutProfile` entry.
#[must_use]
pub fn emit_main_xml() -> String {
    let mut out = schema_header();
    out.push_str("    <kcfgfile name=\"\"/>\n");
    out.push_str("    <group name=\"\">\n");
    // Native entry order: workspaceMode, defaultTiled (schema-only),
    // shortcutProfile (native-only), then the remaining catalog enums and
    // gaps exactly as they stand today.
    let order = [
        "workspaceMode",
        KDE_SCHEMA_ONLY_KEY,
        NATIVE_ONLY_SCHEMA_KEY,
        "sameAxisMove",
        "fixedSizePredicate",
        "bornMaximized",
        "migrationSourceRefill",
        "innerGap",
        "outerGap",
    ];
    for key in order {
        out.push_str(&emit_schema_entry(key));
    }
    out.push_str("    </group>\n</kcfg>\n");
    out
}

fn emit_schema_entry(key: &str) -> String {
    if key == NATIVE_ONLY_SCHEMA_KEY {
        let mut choices = String::new();
        for choice in NATIVE_ONLY_SCHEMA_CHOICES {
            choices.push_str(&format!(
                "                <choice name=\"{choice}\" value=\"{choice}\"/>\n"
            ));
        }
        return format!(
            "        <entry name=\"{key}\" type=\"Enum\">\n\
             {space}<label>{NATIVE_ONLY_SCHEMA_LABEL}</label>\n\
             {space}<default>{NATIVE_ONLY_SCHEMA_DEFAULT}</default>\n\
             {space}<choices>\n\
             {choices}\
             {space}</choices>\n\
             {space2}</entry>\n",
            space = "            ",
            space2 = "        ",
        );
    }
    if key == KDE_SCHEMA_ONLY_KEY {
        let def = settings_catalog::find_field(KDE_SCHEMA_ONLY_FIELD).expect("schema-only def");
        let SettingValue::Bool(_) = def.default else {
            panic!("schema-only default must stay boolean");
        };
        return format!(
            "        <entry name=\"{key}\" type=\"Bool\">\n\
             {space}<label>{KDE_SCHEMA_ONLY_LABEL}</label>\n\
             {space}<default>{}</default>\n\
             {space2}</entry>\n",
            rendered_default(def),
            space = "            ",
            space2 = "        ",
        );
    }
    let field = kde_field(
        KDE_EXPOSED_FIELDS
            .iter()
            .find(|field| field.key == key && field.group == kde_adapter::GROUP_SCRIPT)
            .unwrap_or_else(|| panic!("no exposed script field for {key}"))
            .field_id,
    )
    .expect("exposed script field");
    let def = kde_catalog_def(field).expect("catalog def");
    let tooltip_xml = if field.schema_tooltip.is_empty() {
        String::new()
    } else {
        format!("            <tooltip>{}</tooltip>\n", field.schema_tooltip)
    };
    match def.field_type {
        FieldType::Enum => {
            let mut choices = String::new();
            for option in def.options {
                choices.push_str(&format!(
                    "                <choice name=\"{}\" value=\"{}\"/>\n",
                    option.token, option.token
                ));
            }
            format!(
                "        <entry name=\"{key}\" type=\"Enum\">\n\
                 {space}<label>{}</label>\n\
                 {tooltip}{space}<default>{}</default>\n\
                 {space}<choices>\n\
                 {choices}\
                 {space}</choices>\n\
                 {space2}</entry>\n",
                field.schema_label,
                rendered_default(def),
                tooltip = tooltip_xml,
                space = "            ",
                space2 = "        ",
            )
        }
        FieldType::Int => {
            let (min, max) = (
                def.min_int.expect("int floor"),
                def.max_int.expect("int ceiling"),
            );
            format!(
                "        <entry name=\"{key}\" type=\"Int\">\n\
                 {space}<label>{}</label>\n\
                 {space}<default>{}</default>\n\
                 {space}<min>{min}</min>\n\
                 {space}<max>{max}</max>\n\
                 {space2}</entry>\n",
                field.schema_label,
                rendered_default(def),
                space = "            ",
                space2 = "        ",
            )
        }
        _ => panic!("unexpected script field type for {key}"),
    }
}

fn cpp_escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Emit the consumed C++ descriptor header: tabs, exposed fields in native
/// row order with widget bindings plus both schema and dialog labels, enum
/// options resolved from the catalog with native overrides, and native
/// panel slots with honest placement.
///
/// User-visible strings use `kli18n()`: the KF6 extraction-safe marker for
/// static tables. It evaluates to the raw source string with no dynamic
/// initialization, keeps working inside `constexpr` tables, and is picked up
/// by message extraction once the KCM targets compile this header
/// (translation domain `kwin`). The renderer translates on use
/// (`descriptor.label.toString()`), so no global `QString` is ever
/// constructed here.
#[must_use]
pub fn emit_descriptors_header() -> String {
    let mut out = format!(
        "// Generated by tiler-kde-settings-exporter from the shared catalog. Do not edit.\n\
         //\n\
         // Consumed tab/field/enum metadata for the KDE settings KCMs. The\n\
         // catalog owns defaults, bounds, enum tokens and enum order; this\n\
         // header carries KDE placement (keys, widgets, row order) and the\n\
         // native labels the dialog shows today. `schema_label` is the text\n\
         // in the kcfg/script schema; `ui_label` is the exact widget text in\n\
         // unifiedsettings.ui (colon-terminated where the dialog shows\n\
         // colons) so integration never changes visible text. User-visible\n\
         // strings use kli18n(): raw source strings with no dynamic init,\n\
         // translated by the renderer on use, extraction-safe once compiled\n\
         // into the KCM targets (translation domain \"kwin\"). Ordinary field\n\
         // staging and Save must never invoke the native operation panels\n\
         // listed below.\n\
         #ifndef OMNITILER_KDE_SETTINGS_DESCRIPTORS_H\n\
         #define OMNITILER_KDE_SETTINGS_DESCRIPTORS_H\n\
         \n\
         #include <KLocalizedString>\n\
         #include <KLazyLocalizedString>\n\
         \n\
         namespace OmnitilerKdeSettings\n\
         {{\n\
         \n\
         struct KdeTabDescriptor {{\n\
         {i}const char *tab_id;\n\
         {i}KLazyLocalizedString title;\n\
         {i}const char *page_widget;\n\
         }};\n\
         \n\
         struct KdeEnumOptionDescriptor {{\n\
         {i}const char *token;\n\
         {i}KLazyLocalizedString label;\n\
         {i}KLazyLocalizedString tip;\n\
         }};\n\
         \n\
         struct KdeFieldDescriptor {{\n\
         {i}const char *field_id;\n\
         {i}const char *group;\n\
         {i}const char *key;\n\
         {i}const char *widget;\n\
         {i}KLazyLocalizedString schema_label;\n\
         {i}KLazyLocalizedString ui_label;\n\
         {i}const char *schema_type;\n\
         {i}const char *native_default;\n\
         {i}const char *min_value;\n\
         {i}const char *max_value;\n\
         {i}const KdeEnumOptionDescriptor *options;\n\
         {i}int option_count;\n\
         {i}const char *tab_id;\n\
         }};\n\
         \n\
         struct KdePanelDescriptor {{\n\
         {i}const char *panel_id;\n\
         {i}const char *tab_id;\n\
         {i}const char *placement;\n\
         {i}const char *widget;\n\
         }};\n\
         \n",
        i = "    ",
    );
    out.push_str("inline constexpr KdeTabDescriptor kKdeTabs[] = {\n");
    out.push_str(&format!(
        "// Tiling tab title appears escaped in unifiedsettings.ui as \"{TILING_TAB_UI_SOURCE}\".\n"
    ));
    for tab in KDE_TABS {
        out.push_str(&format!(
            "    {{\"{}\", kli18n(\"{}\"), \"{}\"}},\n",
            tab.tab_id,
            cpp_escape(tab.native_title),
            tab.page_widget
        ));
    }
    out.push_str("};\n\n");
    for field in KDE_EXPOSED_FIELDS {
        let def = kde_catalog_def(field).expect("catalog def");
        if def.field_type != FieldType::Enum {
            continue;
        }
        let array = format!("kOptionsFor{}", cpp_identifier(field.key));
        out.push_str(&format!(
            "inline constexpr KdeEnumOptionDescriptor {array}[] = {{\n"
        ));
        for option in def.options {
            let (label, tip) = kde_option_text(field.field_id, option);
            out.push_str(&format!(
                "    {{\"{}\", kli18n(\"{}\"), kli18n(\"{}\")}},\n",
                option.token,
                cpp_escape(label),
                cpp_escape(tip)
            ));
        }
        out.push_str("};\n\n");
    }
    out.push_str("inline constexpr KdeFieldDescriptor kKdeFields[] = {\n");
    for field in KDE_EXPOSED_FIELDS {
        let def = kde_catalog_def(field).expect("catalog def");
        let section = settings_catalog::find_section(def.section).expect("section");
        let (min_value, max_value) = bounds_text(def);
        let (options, count) = match def.field_type {
            FieldType::Enum => (
                format!("kOptionsFor{}", cpp_identifier(field.key)),
                def.options.len().to_string(),
            ),
            _ => ("nullptr".to_owned(), "0".to_owned()),
        };
        out.push_str(&format!(
            "    {{\"{}\", \"{}\", \"{}\", \"{}\", kli18n(\"{}\"), kli18n(\"{}\"), \"{}\", \"{}\", \"{}\", \"{}\", {}, {}, \"{}\"}},\n",
            field.field_id,
            field.group,
            field.key,
            field.widget,
            cpp_escape(field.schema_label),
            cpp_escape(field.ui_label),
            field.schema_type,
            rendered_default(def),
            min_value,
            max_value,
            options,
            count,
            section.tab
        ));
    }
    out.push_str("};\n\n");
    out.push_str("inline constexpr KdePanelDescriptor kKdePanels[] = {\n");
    for panel in KDE_NATIVE_PANELS {
        out.push_str(&format!(
            "    {{\"{}\", \"{}\", \"{}\", \"{}\"}},\n",
            panel.panel_id, panel.tab_id, panel.placement, panel.widget
        ));
    }
    out.push_str("};\n\n");
    out.push_str(&format!(
        "inline constexpr int kKdeTabCount = {};\n\
         inline constexpr int kKdeExposedFieldCount = {};\n\
         inline constexpr int kKdeNativePanelCount = {};\n\
         \n\
         static_assert(kKdeTabCount == 4, \"four native tabs\");\n\
         static_assert(kKdeExposedFieldCount == 14, \"fourteen exposed fields\");\n\
         static_assert(kKdeNativePanelCount == {}, \"native panels\");\n\
         \n\
         }} // namespace OmnitilerKdeSettings\n\
         \n\
         #endif // OMNITILER_KDE_SETTINGS_DESCRIPTORS_H\n",
        KDE_TABS.len(),
        KDE_EXPOSED_FIELDS.len(),
        KDE_NATIVE_PANELS.len(),
        KDE_NATIVE_PANELS.len()
    ));
    out
}

fn cpp_identifier(key: &str) -> String {
    let mut identifier = String::new();
    let mut upper = true;
    for byte in key.bytes() {
        if byte.is_ascii_alphanumeric() {
            if upper {
                identifier.push(byte.to_ascii_uppercase() as char);
                upper = false;
            } else {
                identifier.push(byte as char);
            }
        } else {
            upper = true;
        }
    }
    identifier
}

fn bounds_text(def: &settings_catalog::FieldDef) -> (String, String) {
    match def.field_type {
        FieldType::Int => (
            def.min_int.expect("int floor").to_string(),
            def.max_int.expect("int ceiling").to_string(),
        ),
        FieldType::Float => {
            let render = |value: f64| {
                if value == -1.0 {
                    "-1".to_owned()
                } else if value.fract() == 0.0 {
                    format!("{value:.1}")
                } else {
                    value.to_string()
                }
            };
            (
                render(def.min_float.expect("float floor")),
                render(def.max_float.expect("float ceiling")),
            )
        }
        _ => ("".to_owned(), "".to_owned()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    fn repo_file(relative: &str) -> String {
        let root = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        std::fs::read_to_string(root.join(relative)).expect("checked-in file readable")
    }

    #[test]
    fn emitted_artifacts_match_checked_in_files_byte_for_byte() {
        for (relative, emit) in ARTIFACTS {
            let current = repo_file(relative);
            assert!(
                contents_match(&current, &emit()),
                "stale artifact {relative}; rerun the exporter"
            );
        }
    }

    #[test]
    fn drift_detector_catches_single_byte_tampering() {
        // Negative control: the comparison backing `--check` must refuse
        // even a one-byte drift in any artifact.
        for (_, emit) in ARTIFACTS {
            let mut tampered = emit();
            let byte = tampered.as_bytes()[tampered.len() / 2];
            let replacement = if byte == b'X' { b'Y' } else { b'X' };
            tampered.replace_range(
                tampered.len() / 2..tampered.len() / 2 + 1,
                &String::from(replacement as char),
            );
            assert!(!contents_match(&tampered, &emit()));
        }
        assert!(contents_match(&emit_kcfg(), &emit_kcfg()));
    }

    #[test]
    fn generated_schemas_preserve_keys_types_and_native_only_values() {
        let kcfg = emit_kcfg();
        for key in [
            "BorderColor",
            "BorderWidth",
            "BorderRadius",
            "BorderGap",
            "UseThemeColor",
            NATIVE_ONLY_KCFG_KEY,
            "GroupUnderlayColor",
            "GroupUnderlayExtension",
        ] {
            assert!(kcfg.contains(&format!("name=\"{key}\"")), "{key}");
        }
        assert!(kcfg.contains(&format!("<default>{NATIVE_ONLY_KCFG_DEFAULT}</default>")));
        assert!(kcfg.contains(NATIVE_ONLY_KCFG_LABEL));
        assert!(!kcfg.contains("Enabled"), "no enable controls may appear");
        // Catalog-owned values flow through: spot-check rendered defaults.
        assert!(kcfg.contains("<default>3.0</default>"));
        assert!(kcfg.contains("<default>-1</default>"));
        assert!(kcfg.contains("<default>#2a82da</default>"));
        let schema = emit_main_xml();
        for key in [
            "workspaceMode",
            "defaultTiled",
            NATIVE_ONLY_SCHEMA_KEY,
            "sameAxisMove",
            "fixedSizePredicate",
            "bornMaximized",
            "migrationSourceRefill",
            "innerGap",
            "outerGap",
        ] {
            assert!(schema.contains(&format!("name=\"{key}\"")), "{key}");
        }
        assert!(schema.contains(&format!("<default>{NATIVE_ONLY_SCHEMA_DEFAULT}</default>")));
        for choice in NATIVE_ONLY_SCHEMA_CHOICES {
            assert!(schema.contains(&format!("name=\"{choice}\" value=\"{choice}\"")));
        }
        assert!(schema.contains("<min>0</min>"));
        assert!(schema.contains("<max>64</max>"));
        assert!(schema.contains("<default>group-with-neighbor</default>"));
        assert!(schema.contains("<default>true</default>"));
    }

    #[test]
    fn header_carries_tabs_fields_enums_and_panels_with_lazy_strings() {
        let header = emit_descriptors_header();
        assert!(header.contains("#ifndef OMNITILER_KDE_SETTINGS_DESCRIPTORS_H"));
        assert!(header.contains("#include <KLocalizedString>"));
        assert!(header.contains("#include <KLazyLocalizedString>"));
        // No eager QString construction: every user-visible string is a
        // raw source string for translation on use. (`kli18n(` necessarily
        // contains the `i18n(` substring; match the eager call form.)
        assert!(!header.contains(" i18n("), "eager i18n() must not appear");
        assert!(!header.contains("QString"));
        for tab in KDE_TABS {
            assert!(header.contains(tab.tab_id));
            assert!(header.contains(tab.page_widget));
        }
        for field in KDE_EXPOSED_FIELDS {
            assert!(header.contains(field.field_id));
            assert!(header.contains(field.group));
            assert!(header.contains(field.key));
            assert!(header.contains(field.widget));
            assert!(header.contains(field.ui_label));
        }
        for panel in KDE_NATIVE_PANELS {
            assert!(header.contains(panel.panel_id));
            assert!(header.contains(panel.widget));
            assert!(header.contains(panel.placement));
        }
        // Schema and dialog labels stay distinct so integration cannot
        // change visible text: the kcfg label has no colon, the widget
        // text does.
        assert!(header.contains("kli18n(\"Fallback border color\")"));
        assert!(header.contains("kli18n(\"Fallback border color:\")"));
        assert!(header.contains("kli18n(\"Per output, local\")"));
        assert!(header.contains("kli18n(\"Gap between tiled windows:\")"));
        assert!(header.contains("static_assert(kKdeExposedFieldCount == 14"));
        assert!(header.contains("\"below-tabs\""));
        let mut widgets = BTreeSet::new();
        for field in KDE_EXPOSED_FIELDS {
            assert!(widgets.insert(field.widget));
        }
    }
}
